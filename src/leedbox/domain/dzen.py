def channel_slug(raw: str) -> str:
    value = raw.strip()
    if "://" not in value:
        value = "https://" + value if value.startswith("dzen.ru/") else value
    if value.startswith("https://"):
        parsed = urlsplit(value)
        if parsed.netloc not in {"dzen.ru", "www.dzen.ru"} or parsed.fragment:
            raise ValueError("Пришлите ссылку на канал https://dzen.ru/имя")
        value = parsed.path.strip("/")
    if not re.fullmatch(r"(?:id/)?[A-Za-z0-9_-]{1,100}", value):
        raise ValueError("Нужна ссылка канала Дзена, не статьи или видео")
    if value in {"a", "b", "video", "news"}:
        raise ValueError("Нужна ссылка канала")
    return value


def period_start(today: date, period: str) -> date:
    if period == "week":
        return today - timedelta(days=6)
    if period not in {"1", "3", "6", "12"}:
        raise ValueError("Неизвестный период")
    index = today.year * 12 + today.month - 1 - int(period)
    year, month0 = divmod(index, 12)
    month = month0 + 1
    return date(year, month, min(today.day, calendar.monthrange(year, month)[1]))


def validated_result(value: Any, count: int = 5) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError("Некорректный результат ИИ")
    for name in ("entities", "markers", "limitations"):
        items = value.get(name)
        if (
            not isinstance(items, list)
            or len(items) > 20
            or any(not isinstance(item, str) or len(item) > 500 for item in items)
        ):
            raise ValueError("Некорректные поля анализа")
    variants = value.get("variants")
    ids = "ABCDE"[:count]
    if count not in {3, 5} or not isinstance(variants, list) or len(variants) != count:
        raise ValueError("Нужно пять заголовков")
    for item, expected in zip(variants, ids, strict=True):
        if not isinstance(item, dict) or item.get("id") != expected:
            raise ValueError("Некорректные варианты")
        for name in ("title", "angle", "rationale"):
            if not isinstance(item.get(name), str) or not 1 <= len(item[name]) <= 500:
                raise ValueError("Неполный вариант")
        if not 20 <= len(item["title"].strip()) <= 160:
            raise ValueError("Заголовок должен содержать 20–160 символов")
    if len({item["title"].casefold() for item in variants}) != count:
        raise ValueError("Заголовки должны отличаться")
    if not isinstance(value.get("recommended_id"), str) or value["recommended_id"] not in set(ids):
        raise ValueError("Некорректная рекомендация")
    return value


def article_prompt(template: str, title: str, inputs: dict[str, Any]) -> str:
    validate_article_template(template)
    # One-pass substitution: user-provided braces are never interpreted.
    replacements = {"title": title, "inputs": json.dumps(inputs, ensure_ascii=False)}
    return re.sub(r"\{\{(title|inputs)\}\}", lambda m: replacements[m[1]], template)


def validate_article_template(template: str) -> None:
    if not 1 <= len(template) <= 10000 or sorted(re.findall(r"\{\{.*?\}\}", template)) != [
        "{{inputs}}",
        "{{title}}",
    ]:
        raise ValueError("Шаблон: до 10000 символов, ровно {{title}} и {{inputs}}")
    remainder = template.replace("{{title}}", "").replace("{{inputs}}", "")
    if any(marker in remainder for marker in ("{{", "}}", "{%", "%}")):
        raise ValueError("Неизвестные переменные или выражения")
